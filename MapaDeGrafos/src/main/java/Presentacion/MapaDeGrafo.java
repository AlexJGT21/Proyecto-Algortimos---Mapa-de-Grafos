    /**
     * Este metodo nos ayuda a evitar seleccionar la misma ciudad
     * Esto funciona cuando se selecciona una ciudad de inicio
     * Eliminando la ciudad destino
     * Motivo: Nos evita recorrer desde inicio a destino desde el mismo origen.
     */
    private void actualizarDestionos() {
        //Primero seleccionamos la ciudad del combo inicio
        comboUno = (Ciudades) jComboInicio.getSelectedItem();
        //Con la ciudad seleciconada, la eliminamos del combo destino.
        jComboDestino.removeItem(comboUno);   
        
        //Ahora para que cada vez que se mantiene en ejecución
        jComboInicio.addItemListener(e -> {
            if(e.getStateChange() == ItemEvent.SELECTED && !actualizado) {
                actualizado = true;
                Ciudades nuevoSeleccionado = (Ciudades) e.getItem();
                
                Object destinoActual = jComboDestino.getSelectedItem();
                
                jComboDestino.removeAllItems();
                
                for (Ciudades ciudad: Ciudades.values()) {
                    if (!ciudad.equals(nuevoSeleccionado)) {
                        jComboDestino.addItem(ciudad);
                    }                    
                }
                
                jComboDestino.setSelectedItem(destinoActual);
                
                actualizado = false;
            }
        });
    }

